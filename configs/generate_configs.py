"""Write every experiment config from one place so all runs share the same settings.

    python configs/generate_configs.py

Edit the constants below, not the generated YAML files.
"""

from __future__ import annotations

import copy
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
SEEDS = (42, 43, 44)
MAIN_TURNS = 3  # history window for the main comparisons and ablations
CONTEXT_TURNS = (1, 3, 5)  # context-length study (k=3 runs are shared with the main comparison)
HEADER = "# Generated by configs/generate_configs.py; edit the generator, not this file.\n"

NEURAL_BASE = {
    "data": {"processed_dir": "data/processed", "max_samples": None},
    "model": {
        "pretrained": "data/pretrained/distilbert-base-uncased",  # written by prepare_data.py
        "utterance_pooling": "cls",
        "dropout": 0.1,
    },
    "context": {"max_utt_tokens": 80},  # per utterance; (5 + 1) * 80 + 7 = 487 <= 512 positions
    "train": {
        "lrs": [2.0e-5, 5.0e-5],  # each tried once; best (lr, epoch) chosen on dev Macro-F1
        "epochs": 5,
        "batch_size": 16,
        "eval_batch_size": 64,
        "weight_decay": 0.01,
        "warmup_ratio": 0.1,
        "max_grad_norm": 1.0,
        "patience": None,  # no early stopping: always up to `epochs`
        "amp": True,  # mixed precision on CUDA only
        "device": "auto",
        "resume": True,
        "log_every": 100,
    },
    "save": {"keep_best_checkpoint": True, "prune_unselected": True},
    "latency": {"batch_size": 1, "max_samples": 300, "warmup": 10},
}

MODELS = {
    "single": {"type": "single"},
    "concat": {"type": "concat"},
    "fixed": {"type": "fusion", "fusion": {"weighting": "equal", "speaker_split": True}},
    "adaptive": {"type": "fusion", "fusion": {"weighting": "learned", "speaker_split": True, "gate_hidden": 256}},
    # ablation: same- and other-speaker history pooled into one source
    "adaptive_merged": {"type": "fusion", "fusion": {"weighting": "learned", "speaker_split": False, "gate_hidden": 256}},
}
# The equal-weights ablation of the adaptive model is the "fixed" model: same encoder, pooling,
# masking and head, gate removed. Trained adaptive runs are also evaluated with equal weights at
# inference (metrics_*_equal_weights.json), so no separate training config is needed.

TFIDF = {
    "model": {"name": "tfidf_lr", "type": "tfidf_lr"},
    "seed": 42,  # lbfgs logistic regression is deterministic, so one run per dataset
    "tfidf_lr": {
        "sublinear_tf": True,
        "max_iter": 2000,
        "grid": {
            "ngram_range": [[1, 1], [1, 2]],
            "min_df": [1, 2],
            "C": [0.1, 0.3, 1.0, 3.0, 10.0],
            "class_weight": [None, "balanced"],
        },
    },
    "latency": {"batch_size": 1, "max_samples": 300, "warmup": 10},
}


def neural_config(dataset: str, model: str, turns: int, seed: int) -> tuple:
    name = f"{model}_s{seed}" if model == "single" else f"{model}_k{turns}_s{seed}"
    run_name = f"{dataset}_{name}"
    cfg = {"run_name": run_name, "seed": seed}
    base = copy.deepcopy(NEURAL_BASE)
    cfg["data"] = {"dataset": dataset, **base["data"]}
    cfg["model"] = {"name": model, **copy.deepcopy(MODELS[model]), **base["model"]}
    cfg["context"] = {"num_turns": 0 if model == "single" else turns, **base["context"]}
    for key in ("train", "save", "latency"):
        cfg[key] = base[key]
    cfg["output_dir"] = f"outputs/runs/{run_name}"
    return Path(dataset) / f"{name}.yaml", cfg


def tfidf_config(dataset: str) -> tuple:
    run_name = f"{dataset}_tfidf_lr"
    cfg = {"run_name": run_name, "seed": TFIDF["seed"], "data": {"dataset": dataset, "processed_dir": "data/processed"},
           "model": TFIDF["model"], "tfidf_lr": TFIDF["tfidf_lr"], "latency": TFIDF["latency"],
           "output_dir": f"outputs/runs/{run_name}"}
    return Path(dataset) / "tfidf_lr.yaml", copy.deepcopy(cfg)


def all_configs():
    yield tfidf_config("meld")
    yield tfidf_config("emorynlp")
    for seed in SEEDS:
        for model in ("single", "concat", "fixed", "adaptive"):
            yield neural_config("meld", model, MAIN_TURNS, seed)
        for model in ("concat", "fixed", "adaptive"):
            yield neural_config("emorynlp", model, MAIN_TURNS, seed)
        yield neural_config("meld", "adaptive_merged", MAIN_TURNS, seed)
        for turns in CONTEXT_TURNS:
            if turns != MAIN_TURNS:
                for model in ("concat", "fixed", "adaptive"):
                    yield neural_config("meld", model, turns, seed)


def main() -> None:
    n = 0
    for rel, cfg in all_configs():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        n += 1
    print(f"wrote {n} configs under {ROOT}")


if __name__ == "__main__":
    main()
